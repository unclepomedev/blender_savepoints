def _with_contexts(messages: Mapping[str, str]) -> dict[tuple[str, str], str]:
    """Register messages under SavePoints' isolated translation context."""
    return {
        (TRANSLATION_CONTEXT, message): translation
        for message, translation in messages.items()
    }


